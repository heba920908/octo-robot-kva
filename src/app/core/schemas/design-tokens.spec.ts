import { buildTokenFiles, findTokenDrift } from '../../../../scripts/design-tokens.mjs';
import { parse } from 'yaml';

const source = `---
title: Fixture
status: final
created: 2026-10-27
updated: 2026-10-27
sources: []
version: alpha
name: Fixture
description: Fixture
colors: {ink: '#1C1714', accent: '#C8875A'}
typography:
  body: {fontFamily: Outfit, fontSize: 16px, fontWeight: '400', lineHeight: '1.6'}
  body-lg: {fontFamily: Outfit, fontSize: 18px, fontWeight: '400', lineHeight: '1.6'}
spacing: {'0': 0px, '4': 16px, target: 44px}
rounded: {none: 0px, DEFAULT: 0px}
elevation: {flat: none, overlay: '0 24px 48px rgba(28, 23, 20, 0.32)'}
motion: {duration: 150ms, easing: 'cubic-bezier(0.2, 0, 0, 1)', scale: '1.03'}
breakpoints: {desktop: 1024px}
components:
  button: {backgroundColor: '{colors.accent}', height: '{spacing.target}', typography: '{typography.body}'}
  focus-ring: {backgroundColor: '{colors.accent}'}
  field-outline: {backgroundColor: '{colors.ink}'}
  divider: {backgroundColor: '{colors.ink}'}
  nav-link-current: {backgroundColor: '{colors.accent}'}
  carousel-thumb-current: {backgroundColor: '{colors.ink}'}
---
Ignored prose.
`;

describe('design token export', () => {
  it('is deterministic, source ordered, and exports all eight groups with generated banners', async () => {
    const first = await buildTokenFiles(source);
    expect(await buildTokenFiles(source)).toEqual(first);
    expect(first.scss.startsWith('// GENERATED by scripts/design-tokens.mjs from DESIGN.md')).toBe(
      true,
    );
    const json = JSON.parse(first.json);
    expect(Object.keys(json)).toEqual([
      '$comment',
      'color',
      'typography',
      'spacing',
      'rounded',
      'elevation',
      'motion',
      'bp',
      'component',
    ]);
    expect(json.$comment).toContain('do not edit. Run npm run tokens:build.');
    expect(json.color.ink).toBe('#1C1714');
    expect(first.scss).toContain('--kva-rounded-default: 0px;');
    expect(first.scss).toContain('--kva-elevation-flat: none;');
    expect(first.scss).toContain('--kva-motion-duration: 150ms;');
    expect(first.scss).toContain('--kva-bp-desktop: 1024px;');
    expect(first.scss.indexOf('--kva-color-ink')).toBeLessThan(
      first.scss.indexOf('--kva-color-accent'),
    );
  });

  it('switches the same typography properties at desktop while retaining both JSON roles', async () => {
    const { scss, json } = await buildTokenFiles(source);
    expect(scss).toContain('--kva-typography-body-font-size: 16px;');
    expect(scss).toMatch(
      /@media \(min-width: 1024px\)[\s\S]*--kva-typography-body-font-size: 18px;/,
    );
    expect(scss).not.toContain('--kva-typography-body-lg-');
    expect(JSON.parse(json).typography['body-lg'].fontSize).toBe('18px');
  });

  it('resolves scalar and typography references and transforms height and stroke properties', async () => {
    const { scss, json } = await buildTokenFiles(source);
    expect(scss).toContain('--kva-component-button-background-color: var(--kva-color-accent);');
    expect(scss).toContain('--kva-component-button-min-height: var(--kva-spacing-target);');
    expect(scss).toContain(
      '--kva-component-button-font-size: var(--kva-typography-body-font-size);',
    );
    expect(scss).not.toContain('--kva-component-button-height:');
    for (const name of [
      'focus-ring',
      'field-outline',
      'divider',
      'nav-link-current',
      'carousel-thumb-current',
    ]) {
      expect(scss).toContain(`--kva-component-${name}-stroke-color:`);
      expect(scss).not.toContain(`--kva-component-${name}-background-color:`);
    }
    expect(JSON.parse(json).component.button).toEqual({
      'background-color': '#C8875A',
      'min-height': '44px',
      'font-family': 'Outfit',
      'font-size': '16px',
      'font-weight': '400',
      'line-height': '1.6',
    });
  });

  it('uses transformed CSS names when referencing literal component properties', async () => {
    const linked = source.replace("height: '{spacing.target}'", 'height: 44px').replace(
      "focus-ring: {backgroundColor: '{colors.accent}'}",
      `focus-ring: {backgroundColor: '#C8875A'}
  alias: {height: '{components.button.height}', backgroundColor: '{components.focus-ring.backgroundColor}'}`,
    );
    const { scss, json } = await buildTokenFiles(linked);
    expect(scss).toContain(
      '--kva-component-alias-min-height: var(--kva-component-button-min-height);',
    );
    expect(scss).toContain(
      '--kva-component-alias-background-color: var(--kva-component-focus-ring-stroke-color);',
    );
    expect(JSON.parse(json).component.alias).toEqual({
      'min-height': '44px',
      'background-color': '#C8875A',
    });
  });

  it.each([
    [source.replace('body-lg:', 'orphan-lg:'), 'typography.orphan-lg'],
    [source.replace('{colors.accent}', '{colors.missing}'), 'components.button.backgroundColor'],
    [source.replace("'#1C1714'", "'red'"), 'colors.ink'],
    [source.replace('16px', '-16px'), 'typography.body.fontSize'],
    [source.replace("'400'", "'heavy'"), 'typography.body.fontWeight'],
    [source.replace("'1.6'", "'bad'"), 'typography.body.lineHeight'],
    [source.replace('target: 44px', 'target: -1px'), 'spacing.target'],
    [source.replace('duration: 150ms', 'duration: forever'), 'motion.duration'],
    [source.replace('desktop: 1024px', 'desktop: nope'), 'breakpoints.desktop'],
    [
      source.replace("height: '{spacing.target}'", 'height: {bad: nested}'),
      'components.button.height',
    ],
    [source.replace('colors:', 'unknown:'), 'unknown'],
    [
      source.replace('---\nIgnored prose.', 'invented: {value: 1}\n---\nIgnored prose.'),
      'invented',
    ],
  ])('rejects invalid source naming its token (%s)', async (invalid, token) => {
    await expect(buildTokenFiles(invalid)).rejects.toThrow(token);
  });

  it('matches the committed artifacts against the real DESIGN source', async () => {
    expect(await findTokenDrift()).toEqual([]);
  });

  it('preserves every real DESIGN token in the resolved JSON export', async () => {
    const moduleName = 'node:fs/promises';
    const fs: { readFile(path: string, encoding: string): Promise<string> } = await import(
      /* @vite-ignore */ moduleName
    );
    const markdown = await fs.readFile(
      '_bmad-output/planning-artifacts/ux-designs/ux-agency-portfolio-2026-10-21/DESIGN.md',
      'utf8',
    );
    const design = parse(markdown.split(/^---\s*$/m)[1]) as Record<
      string,
      Record<string, string | Record<string, string>>
    >;
    const generated = await buildTokenFiles(markdown);
    const exported = JSON.parse(generated.json);
    const [baseScss, desktopScss] = generated.scss.split('@media');
    for (const [role, properties] of Object.entries(design['typography'])) {
      const desktop = role.endsWith('-lg');
      for (const [name, value] of Object.entries(properties)) {
        const property = name.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
        const baseRole = desktop ? role.slice(0, -3) : role;
        expect(desktop ? desktopScss : baseScss, `${role}.${name}`).toContain(
          `--kva-typography-${baseRole}-${property}: ${value};`,
        );
      }
    }
    for (const [sourceGroup, outputGroup] of Object.entries({
      colors: 'color',
      typography: 'typography',
      spacing: 'spacing',
      rounded: 'rounded',
      elevation: 'elevation',
      motion: 'motion',
      breakpoints: 'bp',
    })) {
      expect(exported[outputGroup], sourceGroup).toEqual(design[sourceGroup]);
    }
    expect(Object.keys(exported.component)).toEqual(Object.keys(design['components']));
    for (const [name, properties] of Object.entries(design['components'])) {
      expect(typeof properties).toBe('object');
      const expected: Record<string, string> = {};
      for (const [property, value] of Object.entries(properties)) {
        const path = /^\{(.+)\}$/.exec(value)?.[1].split('.');
        const resolved = path ? design[path[0]][path[1]] : value;
        if (property === 'typography' && typeof resolved === 'object') {
          for (const [typeProperty, typeValue] of Object.entries(resolved)) {
            expected[typeProperty.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`)] =
              typeValue;
          }
        } else {
          const stroke =
            name.startsWith('focus-ring') ||
            name.startsWith('divider') ||
            name.endsWith('-outline') ||
            ['nav-link-current', 'carousel-thumb-current'].includes(name);
          const outputProperty =
            property === 'height'
              ? 'min-height'
              : property === 'backgroundColor' && stroke
                ? 'stroke-color'
                : property.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
          expect(typeof resolved).toBe('string');
          expected[outputProperty] = resolved as string;
        }
      }
      expect(exported.component[name], name).toEqual(expected);
    }
  });

  it('reports changed or missing artifacts and source changes with expected and actual values', async () => {
    const moduleName = 'node:fs/promises';
    const fs: {
      readFile(path: string, encoding: string): Promise<string>;
      writeFile(path: string, content: string): Promise<void>;
      unlink(path: string): Promise<void>;
      mkdir(path: string, options: { recursive: true }): Promise<void>;
      mkdtemp(prefix: string): Promise<string>;
      rm(path: string, options: { recursive: true; force: true }): Promise<void>;
    } = await import(/* @vite-ignore */ moduleName);
    const processModule = 'node:process';
    const runtime: { cwd(): string; execPath: string } = await import(
      /* @vite-ignore */ processModule
    );
    const childModule = 'node:child_process';
    const child: {
      execFile(
        executable: string,
        args: string[],
        options: { cwd: string },
        callback: (error: { code?: number } | null, stdout: string, stderr: string) => void,
      ): void;
    } = await import(/* @vite-ignore */ childModule);
    const temporary = await fs.mkdtemp('/tmp/kva-token-tests-');
    const generator = `${runtime.cwd()}/scripts/design-tokens.mjs`;
    const run = (args: string[]) =>
      new Promise<{ code: number; stdout: string; stderr: string }>((resolve) => {
        child.execFile(runtime.execPath, args, { cwd: temporary }, (error, stdout, stderr) =>
          resolve({ code: error?.code ?? 0, stdout, stderr }),
        );
      });
    const drift = async () => {
      const result = await run([
        '--input-type=module',
        '-e',
        `const {findTokenDrift} = await import(${JSON.stringify(generator)}); console.log(JSON.stringify(await findTokenDrift()));`,
      ]);
      expect(result.code, result.stderr).toBe(0);
      return JSON.parse(result.stdout);
    };
    const designPath =
      '_bmad-output/planning-artifacts/ux-designs/ux-agency-portfolio-2026-10-21/DESIGN.md';
    const scssPath = 'src/styles/_tokens.scss';
    const jsonPath = 'src/app/core/schemas/design-tokens.json';
    const generated = await buildTokenFiles(source);
    try {
      for (const path of [designPath, scssPath, jsonPath]) {
        await fs.mkdir(`${temporary}/${path.slice(0, path.lastIndexOf('/'))}`, { recursive: true });
      }
      await fs.writeFile(`${temporary}/.prettierrc`, await fs.readFile('.prettierrc', 'utf8'));
      await fs.writeFile(`${temporary}/${designPath}`, source);
      const imported = await run([
        '--input-type=module',
        '-e',
        `await import(${JSON.stringify(generator)});`,
      ]);
      expect(imported.code, imported.stderr).toBe(0);
      await expect(fs.readFile(`${temporary}/${scssPath}`, 'utf8')).rejects.toThrow();
      const built = await run([generator]);
      expect(built.code, built.stderr).toBe(0);
      expect(await fs.readFile(`${temporary}/${scssPath}`, 'utf8')).toBe(generated.scss);
      expect(await fs.readFile(`${temporary}/${jsonPath}`, 'utf8')).toBe(generated.json);
      expect((await run([generator, '--check'])).code).toBe(0);
      const edited = generated.scss.replace('--kva-color-ink: #1c1714', '--kva-color-ink: #000000');
      await fs.writeFile(`${temporary}/${scssPath}`, edited);
      expect(await drift()).toContainEqual(
        expect.objectContaining({
          token: '--kva-color-ink',
          expected: '#1c1714',
          actual: '#000000',
        }),
      );
      const checked = await run([generator, '--check']);
      expect(checked.code).toBe(1);
      expect(checked.stderr).toContain('--kva-color-ink');
      expect(await fs.readFile(`${temporary}/${scssPath}`, 'utf8')).toBe(edited);
      await fs.unlink(`${temporary}/${scssPath}`);
      expect(await drift()).toContainEqual(expect.objectContaining({ actual: '<missing>' }));
      expect((await run([generator, '--check'])).code).toBe(1);
      await expect(fs.readFile(`${temporary}/${scssPath}`, 'utf8')).rejects.toThrow();
      await fs.writeFile(`${temporary}/${scssPath}`, generated.scss);
      await fs.writeFile(`${temporary}/${designPath}`, source.replace('#1C1714', '#222222'));
      expect(await drift()).toEqual(
        expect.arrayContaining([
          expect.objectContaining({
            token: '--kva-color-ink',
            expected: '#222222',
            actual: '#1c1714',
          }),
          expect.objectContaining({ token: 'color.ink', expected: '#222222', actual: '#1C1714' }),
        ]),
      );
      await fs.writeFile(
        `${temporary}/${designPath}`,
        source.replace('desktop: 1024px', 'desktop: nope'),
      );
      const invalid = await run([generator]);
      expect(invalid.code).toBe(1);
      expect(invalid.stderr).toContain('breakpoints.desktop');
    } finally {
      await fs.rm(temporary, { recursive: true, force: true });
    }
  }, 15000);
});
